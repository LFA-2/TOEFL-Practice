// Writes the past-paper seed migration for 學測翻譯 from tools/gsat-past.json.
// Usage: node tools/gsat-seed-sql.js > supabase/migrations/20261105000100_gsat_seed.sql
const fs = require('fs');
const path = require('path');

const data = JSON.parse(fs.readFileSync(path.join(__dirname, 'gsat-past.json'), 'utf8'));
const rows = [];
for (const [year, sentences] of Object.entries(data.years)) {
  const y = Number(year);
  const groups = sentences.length === 4 ? [sentences.slice(0, 2), sentences.slice(2, 4)] : [sentences];
  groups.forEach((pair, i) => {
    rows.push({
      source: 'past',
      year: y,
      set: groups.length > 1 ? i + 1 : null,
      label: groups.length > 1 ? `${y} 年・第 ${i + 1} 組` : `${y} 年`,
      sentences: pair.map(zh => ({ zh })),
    });
  });
}
const lit = s => `'${s.replace(/'/g, "''")}'`;
const out = [
  '-- 學測翻譯考古題（大考中心歷屆試題）。Generated by tools/gsat-seed-sql.js from tools/gsat-past.json.',
  `-- ${data._source}`,
  'insert into public.items (type, difficulty, content, source, created_by) values',
  rows.map(r => `  ('gsat', 3, ${lit(JSON.stringify(r))}::jsonb, 'seed', null)`).join(',\n') + ';',
  '',
];
process.stdout.write(out.join('\n'));
