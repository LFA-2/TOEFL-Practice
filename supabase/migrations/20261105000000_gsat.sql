-- 學測翻譯練習: a second subject next to TOEFL.

-- Translation sets live in the shared item bank like the TOEFL items.
alter table public.items drop constraint if exists items_type_check;
alter table public.items add constraint items_type_check
  check (type in ('ctw', 'rdl', 'acad', 'lcr', 'conv', 'ann', 'talk', 'rep', 'interview', 'bas', 'email', 'disc', 'gsat'));

-- Which subjects an account may use. Edit in the Table Editor, e.g. '{gsat}' for a 學測-only account.
alter table public.profiles add column subjects text[] not null default '{toefl,gsat}';

-- Past papers come without reference answers. The first time a set is practised, the
-- generated preparation (split into scoring parts, reference translations, hints) is
-- saved once for everyone. Items are otherwise read-only to users, so this is the only
-- way to change one: it only fills an empty "prep" on a 學測 item.
create function public.gsat_set_prep(p_item int, p_prep jsonb) returns boolean
language plpgsql security definer set search_path = '' as $$
declare n int;
begin
  if not public.is_approved() then
    raise exception 'NOT_APPROVED' using errcode = '42501';
  end if;
  if jsonb_typeof(p_prep) <> 'object' or jsonb_typeof(p_prep -> 'sentences') <> 'array' then
    raise exception 'BAD_PREP' using errcode = '22023';
  end if;
  update public.items set content = content || jsonb_build_object('prep', p_prep)
    where id = p_item and type = 'gsat' and not (content ? 'prep');
  get diagnostics n = row_count;
  return n = 1;
end $$;
revoke execute on function public.gsat_set_prep(int, jsonb) from public, anon;
grant execute on function public.gsat_set_prep(int, jsonb) to authenticated;

-- Phrase book: phrases and sentence patterns saved from feedback, reviewed with spaced repetition.
create table public.gsat_phrases (
  id          int generated by default as identity primary key,
  user_id     uuid not null default auth.uid() references auth.users(id) on delete cascade,
  phrase      text not null,
  zh          text not null default '',
  example     text not null default '',
  example_zh  text not null default '',
  note        text not null default '',
  attempt_id  int references public.attempts(id) on delete set null,
  step        int not null default 0,
  due_day     text not null,
  reps        int not null default 0,
  lapses      int not null default 0,
  last_day    text,
  created_at  timestamptz not null default now(),
  unique (user_id, phrase)
);
create index gsat_phrases_due_idx on public.gsat_phrases (user_id, due_day);

alter table public.gsat_phrases enable row level security;
create policy gsat_phrases_own on public.gsat_phrases for all to authenticated
  using (user_id = (select auth.uid()) and (select public.is_approved()))
  with check (user_id = (select auth.uid()) and (select public.is_approved()));
revoke all on public.gsat_phrases from anon, authenticated;
grant select, insert, update, delete on public.gsat_phrases to authenticated;
grant usage, select on all sequences in schema public to authenticated;
