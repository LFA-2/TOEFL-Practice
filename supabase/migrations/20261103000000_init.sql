-- Your own profile is readable (to see whether you are approved). Nobody can change "approved" through the API.
create policy profiles_select_own on public.profiles for select to authenticated
  using (id = (select auth.uid()));

create policy ai_usage_select_own on public.ai_usage for select to authenticated
  using (user_id = (select auth.uid()));

create policy items_select on public.items for select to authenticated
  using ((select public.is_approved()));
create policy items_insert on public.items for insert to authenticated
  with check ((select public.is_approved()) and created_by = (select auth.uid()));

do $$
declare t text;
begin
  foreach t in array array['user_locks', 'attempts', 'skills', 'skill_history', 'plans', 'settings', 'words', 'word_reviews'] loop
    execute format(
      'create policy %I on public.%I for all to authenticated
         using (user_id = (select auth.uid()) and (select public.is_approved()))
         with check (user_id = (select auth.uid()) and (select public.is_approved()))',
      t || '_own', t);
  end loop;
end $$;

-- ---------------------------------------------------------------- privileges
-- Supabase grants everything on new tables by default; start from nothing and grant only what is needed.
revoke all on all tables in schema public from anon, authenticated;
revoke all on all sequences in schema public from anon, authenticated;
grant select on public.profiles, public.ai_usage to authenticated;
grant select, insert on public.items to authenticated;
grant select, insert, update, delete on
  public.user_locks, public.attempts, public.skills, public.skill_history,
  public.plans, public.settings, public.words, public.word_reviews to authenticated;
grant usage, select on all sequences in schema public to authenticated;

revoke execute on function public.consume_ai_call() from public, anon;
revoke execute on function public.ai_quota_status() from public, anon;
grant execute on function public.ai_quota_status() to authenticated;
revoke execute on function public.is_approved() from public, anon;
revoke execute on function public.handle_new_user() from public, anon, authenticated;
grant execute on function public.consume_ai_call() to authenticated;
grant execute on function public.is_approved() to authenticated;
