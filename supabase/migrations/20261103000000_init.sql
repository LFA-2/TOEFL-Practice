-- TOEFL Coach on Supabase: accounts with manual approval, per-user practice data, AI quota.
-- Every per-user table is protected by Row Level Security: a user can only read and write
-- their own rows, and only after their account has been approved.

-- ---------------------------------------------------------------- accounts
create table public.profiles (
  id             uuid primary key references auth.users(id) on delete cascade,
  email          text,
  approved       boolean not null default false,   -- set to true by hand in the Table Editor
  ai_daily_limit int,                               -- per-user override; null = app_config default
  created_at     timestamptz not null default now()
);

create function public.handle_new_user() returns trigger
language plpgsql security definer set search_path = '' as $$
begin
  insert into public.profiles (id, email) values (new.id, new.email) on conflict (id) do nothing;
  return new;
end $$;

create trigger on_auth_user_created after insert on auth.users
  for each row execute function public.handle_new_user();

create function public.is_approved() returns boolean
language sql stable security definer set search_path = '' as $$
  select coalesce((select approved from public.profiles where id = auth.uid()), false)
$$;

-- ---------------------------------------------------------------- AI quota
create table public.app_config (
  key   text primary key,
  value jsonb not null
);
insert into public.app_config (key, value) values
  ('ai_daily_limit', '30'),          -- Claude calls per user per day (Taipei time)
  ('ai_global_daily_limit', '300');  -- all users together, a last line of defence

create table public.ai_usage (
  user_id uuid not null references auth.users(id) on delete cascade,
  day     text not null,
  calls   int  not null default 0,
  primary key (user_id, day)
);

-- Counts one Claude call for the current user. Raises AI_QUOTA (and counts nothing) when over a limit.
create function public.consume_ai_call() returns int
language plpgsql security definer set search_path = '' as $$
declare
  uid   uuid := auth.uid();
  d     text := to_char(now() at time zone 'Asia/Taipei', 'YYYY-MM-DD');
  lim   int;
  glim  int;
  used  int;
  total int;
begin
  if uid is null or not public.is_approved() then
    raise exception 'NOT_APPROVED' using errcode = '42501';
  end if;
  select coalesce(p.ai_daily_limit, (select (value #>> '{}')::int from public.app_config where key = 'ai_daily_limit'), 30)
    into lim from public.profiles p where p.id = uid;
  select coalesce((select (value #>> '{}')::int from public.app_config where key = 'ai_global_daily_limit'), 300) into glim;

  insert into public.ai_usage (user_id, day, calls) values (uid, d, 1)
    on conflict (user_id, day) do update set calls = public.ai_usage.calls + 1
    returning calls into used;
  if used > lim then
    raise exception 'AI_QUOTA' using errcode = 'P0001';
  end if;
  select sum(calls) into total from public.ai_usage where day = d;
  if total > glim then
    raise exception 'AI_QUOTA_GLOBAL' using errcode = 'P0001';
  end if;
  return lim - used;
end $$;

-- What the settings page shows: calls used today and the limit that applies to this user.
create function public.ai_quota_status() returns jsonb
language sql stable security definer set search_path = '' as $$
  select jsonb_build_object(
    'used', coalesce((select calls from public.ai_usage
                      where user_id = auth.uid() and day = to_char(now() at time zone 'Asia/Taipei', 'YYYY-MM-DD')), 0),
    'limit', coalesce((select ai_daily_limit from public.profiles where id = auth.uid()),
                      (select (value #>> '{}')::int from public.app_config where key = 'ai_daily_limit'), 30))
$$;

-- Short-lived per-user locks, so two requests never generate the same thing twice.
create table public.user_locks (
  user_id uuid not null default auth.uid() references auth.users(id) on delete cascade,
  name    text not null,
  until   timestamptz not null,
  primary key (user_id, name)
);

-- ---------------------------------------------------------------- practice
-- Items are shared by all approved users, so one generated passage can serve everyone.
create table public.items (
  id          int generated by default as identity primary key,
  type        text not null check (type in ('ctw', 'rdl', 'acad', 'bas', 'email', 'disc')),
  difficulty  double precision not null,
  content     jsonb not null,
  source      text not null default 'ai',
  created_by  uuid default auth.uid() references auth.users(id) on delete set null,
  created_at  timestamptz not null default now()
);
create index items_type_idx on public.items (type, difficulty);

create table public.attempts (
  id          int generated by default as identity primary key,
  user_id     uuid not null default auth.uid() references auth.users(id) on delete cascade,
  item_id     int not null references public.items(id),
  type        text not null,
  mode        text not null default 'practice',
  response    jsonb not null,
  score       double precision not null,
  raw_score   double precision,
  max_score   double precision,
  feedback    jsonb,
  seconds     int,
  day         text not null,
  created_at  timestamptz not null default now()
);
create index attempts_user_day_idx on public.attempts (user_id, day);
create index attempts_user_item_idx on public.attempts (user_id, item_id);

create table public.skills (
  user_id    uuid not null default auth.uid() references auth.users(id) on delete cascade,
  type       text not null,
  rating     double precision not null,
  n          int not null default 0,
  updated_at timestamptz not null default now(),
  primary key (user_id, type)
);

create table public.skill_history (
  id      int generated by default as identity primary key,
  user_id uuid not null default auth.uid() references auth.users(id) on delete cascade,
  type    text not null,
  rating  double precision not null,
  day     text not null
);
create index skill_history_user_idx on public.skill_history (user_id, id);

create table public.plans (
  user_id uuid not null default auth.uid() references auth.users(id) on delete cascade,
  day     text not null,
  tasks   jsonb not null,
  primary key (user_id, day)
);

create table public.settings (
  user_id uuid not null default auth.uid() references auth.users(id) on delete cascade,
  key     text not null,
  value   jsonb not null,
  primary key (user_id, key)
);

-- ---------------------------------------------------------------- vocabulary
create table public.words (
  id          int generated by default as identity primary key,
  user_id     uuid not null default auth.uid() references auth.users(id) on delete cascade,
  word        text not null,
  topic       text,
  band        double precision,
  status      text not null default 'pool' check (status in ('pool', 'known', 'learning')),
  mark        text,
  card        jsonb,
  step        int not null default 0,
  due_day     text,
  reps        int not null default 0,
  lapses      int not null default 0,
  marked_day  text,
  created_at  timestamptz not null default now(),
  unique (user_id, word)
);
create index words_user_status_idx on public.words (user_id, status, due_day);
create index words_user_marked_idx on public.words (user_id, marked_day);

create table public.word_reviews (
  id         int generated by default as identity primary key,
  user_id    uuid not null default auth.uid() references auth.users(id) on delete cascade,
  word_id    int not null references public.words(id) on delete cascade,
  day        text not null,
  mode       text not null,
  result     text not null,
  free       boolean not null default false,
  created_at timestamptz not null default now()
);
create index word_reviews_user_day_idx on public.word_reviews (user_id, day);

